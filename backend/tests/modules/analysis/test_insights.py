import uuid
import pytest
import json
from unittest.mock import AsyncMock, MagicMock, patch
from app.modules.analysis.models import Analysis, TopicCluster


@pytest.mark.asyncio
async def test_generate_insights_successful():
    """Should successfully fetch clusters, call LLM, re-label clusters, and save insights."""
    analysis_id = uuid.uuid4()
    video_id = uuid.uuid4()

    # Mock Analysis object
    mock_analysis = MagicMock(spec=Analysis)
    mock_analysis.id = analysis_id
    mock_analysis.status = "pending"
    mock_analysis.error_message = None

    # Mock TopicCluster object
    mock_cluster = MagicMock(spec=TopicCluster)
    mock_cluster.id = uuid.uuid4()
    mock_cluster.title = "Old Cluster Title"
    mock_cluster.summary = "Old summary snippet"
    mock_cluster.size = 10
    mock_cluster.sentiment_score = 0.5

    mock_db = AsyncMock()
    
    # We execute:
    # 1. Fetch analysis
    # 2. Fetch clusters
    # 3. Fetch comments in the cluster (for _get_representative_comments)
    mock_result_analysis = MagicMock()
    mock_result_analysis.scalars.return_value.first.return_value = mock_analysis
    
    mock_result_clusters = MagicMock()
    mock_result_clusters.scalars.return_value.all.return_value = [mock_cluster]

    mock_result_comments = MagicMock()
    mock_result_comments.scalars.return_value.all.return_value = [] # no comments for representatives helper, falls back

    mock_db.execute.side_effect = [
        mock_result_analysis,
        mock_result_clusters,
        mock_result_comments
    ]

    added_insights = []
    def mock_add(instance):
        from app.modules.analysis.models import Insight
        if isinstance(instance, Insight):
            added_insights.append(instance)

    mock_db.add = mock_add

    # Mock LLM JSON output matching the expected schema
    mock_json_response = {
        "topic_clusters": [
            {
                "name": "New Re-labeled Title",
                "description": "Clean description of this cluster generated by LLM."
            }
        ],
        "top_questions": [
            {
                "title": "What is the cost?",
                "content": "Users ask about the core pricing model."
            }
        ],
        "pain_points": [
            {
                "title": "Slow load times",
                "content": "Users describe experiencing delays when loading dashboards."
            }
        ],
        "positive_themes": [
            {
                "title": "Aesthetic interface",
                "content": "Users praise the dark green layout design."
            }
        ],
        "content_recommendations": [
            {
                "title": "Pricing Video Tutorial",
                "content": "Create a tutorial explaining setup and pricing."
            }
        ]
    }

    # Mock Groq completions integration call
    with patch(
        "app.modules.analysis.services.generate_chat_completion",
        new_callable=AsyncMock,
        return_value=json.dumps(mock_json_response)
    ) as mock_llm_call:

        from app.modules.analysis.services import generate_insights_for_analysis
        result_data = await generate_insights_for_analysis(mock_db, analysis_id, video_id)

        assert result_data == mock_json_response
        mock_llm_call.assert_called_once()
        mock_db.commit.assert_called()

        # Verify cluster re-labeling
        assert mock_cluster.title == "New Re-labeled Title"
        assert mock_cluster.summary == "Clean description of this cluster generated by LLM."

        # Verify analysis status completed
        assert mock_analysis.status == "completed"

        # Verify insights created
        assert len(added_insights) == 4
        types = [i.type for i in added_insights]
        assert "question" in types
        assert "pain_point" in types
        assert "positive_theme" in types
        assert "recommendation" in types

        # Check detail matching
        recommendation_insight = next(i for i in added_insights if i.type == "recommendation")
        assert recommendation_insight.title == "Pricing Video Tutorial"
        assert recommendation_insight.content == "Create a tutorial explaining setup and pricing."


@pytest.mark.asyncio
async def test_generate_insights_llm_failure():
    """Should set analysis status to failed and store error message on exception."""
    analysis_id = uuid.uuid4()
    video_id = uuid.uuid4()

    mock_analysis = MagicMock(spec=Analysis)
    mock_analysis.id = analysis_id
    mock_analysis.status = "pending"
    mock_analysis.error_message = None

    mock_db = AsyncMock()
    
    mock_result_analysis = MagicMock()
    mock_result_analysis.scalars.return_value.first.return_value = mock_analysis
    mock_db.execute.return_value = mock_result_analysis

    # Mock Groq completions call to raise exception
    with patch(
        "app.modules.analysis.services.generate_chat_completion",
        new_callable=AsyncMock,
        side_effect=Exception("API Key validation error")
    ):
        from app.modules.analysis.services import generate_insights_for_analysis
        
        with pytest.raises(Exception, match="API Key validation error"):
            await generate_insights_for_analysis(mock_db, analysis_id, video_id)

        # Check status is set to failed
        assert mock_analysis.status == "failed"
        assert "API Key validation error" in mock_analysis.error_message
        mock_db.commit.assert_called()
